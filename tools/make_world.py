"""Generate the Webots world (worlds/valet_parking.wbt) from the SAME lot
model used by the planner, so geometry in Webots and in Python can never
drift apart. Also writes worlds/lot_config.json, which the Webots
controller reads as the "infrastructure" message (slot occupancy and the
boxes of the parked cars).

Usage:
    python tools/make_world.py --seed 3 --occupancy 0.7 --pedestrians 1
"""
import argparse
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from valet.config import DEFAULT          # noqa: E402
from valet.lot import make_scenario       # noqa: E402

WEBOTS_TAG = "R2025a"
PROTO = f"https://raw.githubusercontent.com/cyberbotics/webots/{WEBOTS_TAG}/projects"

HEADER = f"""#VRML_SIM {WEBOTS_TAG} utf8

EXTERNPROTO "{PROTO}/objects/backgrounds/protos/TexturedBackground.proto"
EXTERNPROTO "{PROTO}/objects/backgrounds/protos/TexturedBackgroundLight.proto"
EXTERNPROTO "{PROTO}/vehicles/protos/bmw/BmwX5.proto"
EXTERNPROTO "{PROTO}/humans/pedestrian/protos/Pedestrian.proto"

WorldInfo {{
  info [
    "G14 - Autonomous Valet Parking Agent (CSAI4014 AISR, P13)"
    "Generated by tools/make_world.py - do not edit by hand"
  ]
  title "Autonomous Valet Parking"
  basicTimeStep 16
  coordinateSystem "ENU"
}}
Viewpoint {{
  orientation -0.42 0.42 0.80 1.79
  position 20 -22 38
  near 1
}}
TexturedBackground {{
}}
TexturedBackgroundLight {{
}}
"""

CAR_COLOURS = ["0.75 0.1 0.1", "0.1 0.25 0.7", "0.85 0.85 0.85", "0.15 0.15 0.15",
               "0.6 0.6 0.65", "0.1 0.5 0.25", "0.9 0.7 0.1"]


def box_solid(name, cx, cy, z, yaw, lx, ly, lz, colour, collide=True):
    bo = f"""
  boundingObject Pose {{ translation 0 0 0 children [ Box {{ size {lx:.3f} {ly:.3f} {lz:.3f} }} ] }}""" \
        if collide else ""
    return f"""Solid {{
  translation {cx:.3f} {cy:.3f} {z:.3f}
  rotation 0 0 1 {yaw:.4f}
  name "{name}"
  children [
    Shape {{
      appearance PBRAppearance {{ baseColor {colour} roughness 0.6 metalness 0 }}
      geometry Box {{ size {lx:.3f} {ly:.3f} {lz:.3f} }}
    }}
  ]{bo}
}}
"""


def floor(lp):
    W, H = lp.width, lp.height
    return f"""Solid {{
  translation {W/2:.3f} {H/2:.3f} -0.05
  name "asphalt"
  children [
    Shape {{
      appearance PBRAppearance {{ baseColor 0.25 0.25 0.27 roughness 1 metalness 0 }}
      geometry Box {{ size {W:.3f} {H:.3f} 0.1 }}
    }}
  ]
  boundingObject Box {{ size {W:.3f} {H:.3f} 0.1 }}
  locked TRUE
}}
"""


def slot_lines(slots, p):
    lp = p.lot
    out = []
    for s in slots:
        # two side lines per slot (0.1 m wide painted lines, no collision)
        for k, dx in enumerate((-lp.slot_width / 2, lp.slot_width / 2)):
            out.append(box_solid(f"line_{s.sid}_{k}", s.cx + dx, s.cy, 0.002, 0.0,
                                 0.1, lp.slot_depth, 0.004, "1 1 1", collide=False))
    return "".join(out)


def sensor_nodes(p):
    """DistanceSensors in the BmwX5 sensorsSlotCenter (origin = rear axle)."""
    out = []
    for name, x, y, yaw in p.sensors.mounts:
        out.append(f"""      DistanceSensor {{
        translation {x:.3f} {y:.3f} 0.5
        rotation 0 0 1 {yaw:.4f}
        name "{name}"
        lookupTable [ 0 0 0, {p.sensors.max_range:.1f} {p.sensors.max_range:.1f} {p.sensors.noise_std / p.sensors.max_range:.4f} ]
      }}
""")
    return "".join(out)


def ego_car(start, p, controller_args):
    x, y, yaw = start
    args = " ".join(f'"{a}"' for a in controller_args)
    return f"""BmwX5 {{
  translation {x:.3f} {y:.3f} 0.4
  rotation 0 0 1 {yaw:.4f}
  name "valet_car"
  controller "valet_parking"
  controllerArgs [ {args} ]
  sensorsSlotCenter [
      GPS {{
        name "gps"
        accuracy 0.05
      }}
      InertialUnit {{
        name "imu"
      }}
{sensor_nodes(p)}  ]
}}
"""


def pedestrian_node(i, ped):
    return f"""Pedestrian {{
  translation {ped.ax:.2f} {ped.ay:.2f} 1.27
  name "pedestrian_{i}"
  controller "pedestrian"
  controllerArgs [ "--trajectory={ped.ax:.2f} {ped.ay:.2f}, {ped.bx:.2f} {ped.by:.2f}" "--speed={ped.speed:.2f}" ]
}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=3)
    ap.add_argument("--occupancy", type=float, default=0.7)
    ap.add_argument("--pedestrians", type=int, default=1)
    ap.add_argument("--planner", default="hybrid", choices=["hybrid", "grid"])
    ap.add_argument("--law", default="pure_pursuit", choices=["pure_pursuit", "stanley"])
    ap.add_argument("--reflex", default="ttc", choices=["none", "fixed", "ttc"])
    ap.add_argument("--selector", default="utility", choices=["utility", "nearest"])
    ap.add_argument("--out", default=os.path.join(ROOT, "worlds", "valet_parking.wbt"))
    a = ap.parse_args()

    p = DEFAULT
    sc = make_scenario(a.seed, a.occupancy, a.pedestrians, p=p)
    parts = [HEADER, floor(p.lot), slot_lines(sc.slots, p)]
    for k, w in enumerate(sc.walls):
        h = 1.0 if k < 4 else 0.15                      # kerb between rows B and C is low
        parts.append(box_solid(f"wall_{k}", w.cx, w.cy, h / 2, w.yaw, w.length, w.width, h,
                               "0.7 0.7 0.7"))
    for k, b in enumerate(sc.parked):
        parts.append(box_solid(f"parked_{k}", b.cx, b.cy, 0.75, b.yaw, b.length, b.width, 1.5,
                               CAR_COLOURS[k % len(CAR_COLOURS)]))
    ctrl_args = [f"--planner={a.planner}", f"--law={a.law}", f"--reflex={a.reflex}",
                 f"--selector={a.selector}"]
    parts.append(ego_car(sc.start, p, ctrl_args))
    for i, ped in enumerate(sc.pedestrians):
        parts.append(pedestrian_node(i, ped))
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write("".join(parts))

    cfg = {"seed": a.seed, "occupancy": a.occupancy,
           "start": sc.start, "exit_point": sc.exit_point,
           "occupied": [s.sid for s in sc.slots if s.occupied],
           "parked": [[b.cx, b.cy, b.yaw, b.length, b.width] for b in sc.parked],
           "walls": [[w.cx, w.cy, w.yaw, w.length, w.width] for w in sc.walls]}
    with open(os.path.join(os.path.dirname(a.out), "lot_config.json"), "w") as f:
        json.dump(cfg, f, indent=1)
    print(f"wrote {a.out}  ({len(sc.parked)} parked cars, {len(sc.free_slots())} free slots)")


if __name__ == "__main__":
    main()
